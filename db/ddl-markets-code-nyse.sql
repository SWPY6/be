-- markets.code enum 에 NYSE 를 더한다.
-- 명세: docs/SPEC-stock-master.md 「선행 조건 ①」
--
-- 왜
--   해외 종목을 거래소 단위로 담는다 — 나스닥 3,948 · 뉴욕 2,461. 지금 enum 에 NYSE 가 없어
--   뉴욕 종목을 담을 시장이 없다.
--
--   SP500 을 쓰지 않는다. S&P 500 은 지수이고 구성 종목이 나스닥과 뉴욕에 걸쳐 있다. 지수를
--   시장으로 쓰면 애플이 NASDAQ 과 SP500 둘에 속하고, 그러면 StockMoverService.matchByTicker
--   가 "한 종목코드에 둘 이상 걸리면 넣지 않는다"는 규칙으로 그 종목을 버린다 — 사용자가 가장
--   많이 찾는 500개가 stockId: null 이 된다.
--   실측으로 확인했다: 나스닥·뉴욕 파일에 겹치는 티커가 0 이고, 코스피·코스닥도 0 이다.
--   그래서 거래소 단위로 두면 모든 티커가 정확히 한 시장에만 속한다.
--
--   SP500 을 enum 에서 지우지 않는다. 기존 해외 36종목이 아직 그 값을 쓰고 있어, 먼저 지우면
--   읽기가 깨진다. 종목을 옮긴 뒤(db/seed-markets.sql)에도 값은 남겨 둔다 — enum 에서 값을
--   빼는 ALTER 는 그 값을 쓰는 행이 하나도 없어야 하고, 얻는 게 없다.
--
-- NYSE 를 목록 끝에 붙인다
--   MySQL enum 은 문자열이 아니라 순서 번호를 저장한다. 끝에 붙이면 기존 값의 번호가 그대로라
--   ALGORITHM=INPLACE 로 끝나고, 중간에 끼우면 SP500 의 번호가 밀려 테이블을 복사한다.
--   72행이라 성능 차이는 없지만, 기존 값을 건드리지 않는 쪽이 안전하다.
--
--   그래서 Hibernate 가 생성할 순서(알파벳: KOSDAQ, KOSPI, NASDAQ, NYSE, SP500)와 다르다.
--   @Enumerated(STRING) 은 읽고 쓸 때 문자열을 주고받으므로 순서는 동작에 영향이 없다.
--   나중에 엔티티에서 DDL 을 다시 생성해 비교하면 순서가 달라 보이는데, 틀린 것이 아니다.

